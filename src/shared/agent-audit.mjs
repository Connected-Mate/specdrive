import fs from 'node:fs/promises'
import { constants } from 'node:fs'
import path from 'node:path'
import os from 'node:os'
import { randomUUID, createHash } from 'node:crypto'
import { collectHistory } from './agent-history.mjs'
import { previewAudit } from './audit-preview.mjs'

const MAX_TARGET_BYTES = 1024 * 1024
const MAX_REPORT_BYTES = 8 * 1024 * 1024
const MAX_HISTORY_BYTES = 20 * 1024 * 1024
const UUID = /^[0-9a-f]{8}-[0-9a-f]{4}-4[0-9a-f]{3}-[89ab][0-9a-f]{3}-[0-9a-f]{12}$/
const SESSION_ID = /^[0-9a-f]{32}$/
const hash = value => createHash('sha256').update(value).digest('hex')
const nextTimestamp = previous => new Date(Math.max(Date.now(), (Date.parse(previous) || 0) + 1)).toISOString()
const generated = value => /<!--\s*Generated by SpecDrive\b/i.test(value)
const fail = message => { throw new Error(message) }
const string = (value, name, max = 10_000, empty = false) => {
  if (typeof value !== 'string' || value.length > max || (!empty && !value.trim())) fail(`${name} must be ${empty ? '' : 'nonempty '}text of at most ${max} characters.`)
  return value
}
const array = (value, name, max) => { if (!Array.isArray(value) || value.length > max) fail(`${name} must be an array of at most ${max} entries.`); return value }
const enumeration = (value, choices, name) => { if (!choices.includes(value)) fail(`Invalid ${name}.`); return value }

async function storeRoot() {
  const root = path.resolve(process.env.SPECDRIVE_DATA_DIR || path.join(os.homedir(), '.specdrive'), 'agent-audits')
  await fs.mkdir(root, { recursive: true, mode: 0o700 })
  if ((await fs.lstat(root)).isSymbolicLink()) fail('The audit store must not be a symbolic link.')
  return fs.realpath(root)
}
async function auditDirectory(id) {
  if (typeof id !== 'string' || !UUID.test(id)) fail('Invalid audit ID.')
  const directory = path.join(await storeRoot(), id)
  const stat = await fs.lstat(directory)
  if (!stat.isDirectory() || stat.isSymbolicLink() || await fs.realpath(directory) !== directory) fail('Invalid audit directory.')
  return directory
}
async function readBounded(file, max) {
  const handle = await fs.open(file, constants.O_RDONLY | constants.O_NOFOLLOW)
  try {
    const stat = await handle.stat()
    if (!stat.isFile() || stat.size > max) fail('File is not regular or exceeds the permitted size.')
    const buffer = Buffer.alloc(stat.size + 1)
    let used = 0
    while (used < buffer.length) { const result = await handle.read(buffer, used, buffer.length - used, used); if (!result.bytesRead) break; used += result.bytesRead }
    if (used > stat.size || used > max) fail('File changed while it was being read; retry the operation.')
    return { text: new TextDecoder('utf-8', { fatal: true }).decode(buffer.subarray(0, used)), stat }
  } finally { await handle.close() }
}
async function atomicJSON(file, data, max = MAX_REPORT_BYTES) {
  const text = JSON.stringify(data, null, 2) + '\n'
  if (Buffer.byteLength(text) > max) fail('Audit data exceeds the permitted size.')
  const temporary = `${file}.${randomUUID()}.tmp`
  let handle
  try {
    handle = await fs.open(temporary, constants.O_WRONLY | constants.O_CREAT | constants.O_EXCL | constants.O_NOFOLLOW, 0o600)
    await handle.writeFile(text, 'utf8')
    await handle.sync()
    await handle.close(); handle = undefined
    await fs.rename(temporary, file)
  } finally { await handle?.close(); await fs.unlink(temporary).catch(error => { if (error.code !== 'ENOENT') throw error }) }
}
async function loadReport(directory, id) {
  const report = JSON.parse((await readBounded(path.join(directory, 'report.json'), MAX_REPORT_BYTES)).text)
  if (report.id !== id || !Array.isArray(report.sessions) || typeof report.original !== 'string' || report.originalHash !== hash(report.original)) fail('Invalid audit report.')
  return report
}

/** Targets must be explicit instruction files. Resolve the parent once and keep
 * the canonical path in the snapshot; never follow a target-file symlink. */
async function canonicalTarget(targetPath) {
  if (typeof targetPath !== 'string' || !path.isAbsolute(targetPath) || !['CLAUDE.md', 'AGENTS.md'].includes(path.basename(targetPath))) fail('Choose an absolute path named CLAUDE.md or AGENTS.md.')
  const parent = await fs.realpath(path.dirname(targetPath))
  if (!(await fs.stat(parent)).isDirectory()) fail('The instruction file parent must be a directory.')
  const canonical = path.join(parent, path.basename(targetPath))
  try {
    const stat = await fs.lstat(canonical)
    if (stat.isSymbolicLink() || !stat.isFile()) fail('Instruction targets must be regular files, not symbolic links.')
    if (stat.nlink !== 1) fail('Instruction targets with hard links are not supported.')
  } catch (error) { if (error.code !== 'ENOENT') throw error }
  return canonical
}
async function snapshot(targetPath) {
  try {
    const { text, stat } = await readBounded(targetPath, MAX_TARGET_BYTES)
    if (stat.nlink !== 1) fail('Instruction targets with hard links are not supported.')
    if (generated(text)) fail('This AGENTS.md is generated by SpecDrive. Choose a personal CLAUDE.md or a handwritten AGENTS.md instead.')
    return { original: text, originalHash: hash(text), originalExists: true, mode: stat.mode & 0o777 }
  } catch (error) {
    if (error.code !== 'ENOENT') throw error
    return { original: '', originalHash: hash(''), originalExists: false, mode: 0o600 }
  }
}
async function verifySnapshot(report) {
  if (await canonicalTarget(report.targetPath) !== report.targetPath) fail('The target directory has changed; start a new audit.')
  const current = await snapshot(report.targetPath)
  if (current.originalExists !== report.originalExists || current.originalHash !== report.originalHash) fail('The instruction file changed since this audit. Start a new audit before applying proposals.')
  return current
}
async function withAuditLock(id, action) {
  const directory = await auditDirectory(id)
  const lock = path.join(directory, '.write.lock')
  let handle
  try {
    try { handle = await fs.open(lock, constants.O_WRONLY | constants.O_CREAT | constants.O_EXCL | constants.O_NOFOLLOW, 0o600) }
    catch (error) { if (error.code === 'EEXIST') fail('This audit is already being updated. Retry after the current operation completes.'); throw error }
    return await action(directory, await loadReport(directory, id))
  } finally { if (handle) { await handle.close(); await fs.unlink(lock) } }
}

/** Start a local, bounded snapshot. This never edits the target instruction file. */
export async function startAudit({ targetPath, projectPath, limit = 100, providers = ['claude', 'codex'] }) {
  const canonical = await canonicalTarget(targetPath)
  const original = await snapshot(canonical)
  if (projectPath !== undefined && (typeof projectPath !== 'string' || !path.isAbsolute(projectPath))) fail('Project scope must be an absolute directory path.')
  const project = projectPath ? await fs.realpath(projectPath) : undefined
  const history = await collectHistory({ projectPath: project, limit, providers })
  if (path.basename(canonical) === 'AGENTS.md') {
    try {
      await fs.lstat(path.join(path.dirname(canonical), 'AGENTS.override.md'))
      history.limitations.push('AGENTS.override.md is present beside this target and takes precedence for Codex; changes to AGENTS.md may not be used while that override exists.')
    } catch (error) { if (error.code !== 'ENOENT') throw error }
  }
  const id = randomUUID()
  const now = new Date().toISOString()
  const report = { id, createdAt: now, updatedAt: now, status: 'collecting', targetPath: canonical,
    original: original.original, originalHash: original.originalHash, originalExists: original.originalExists,
    scope: project ? `Recent local sessions for ${project} (up to ${limit}; no cloud access).` : `Recent local Claude/Codex sessions (up to ${limit}; no cloud access).`,
    coverage: history.coverage, sessions: history.histories.map(item => item.session), findings: [], observations: [], limitations: history.limitations }
  const directory = path.join(await storeRoot(), id)
  await fs.mkdir(directory, { mode: 0o700 })
  try {
    for (const item of history.histories) await atomicJSON(path.join(directory, `${item.session.id}.json`), item, MAX_HISTORY_BYTES)
    await atomicJSON(path.join(directory, 'report.json'), report)
  } catch (error) { await fs.rm(directory, { recursive: true, force: true }); throw error }
  return report
}

export async function listAudits() {
  const root = await storeRoot()
  const items = []
  // Avoid reading arbitrary directories or an unbounded set of report files.
  const directories = (await fs.readdir(root, { withFileTypes: true })).filter(entry => entry.isDirectory() && UUID.test(entry.name))
  const recent = []
  for (const directory of directories.slice(0, 2_000)) {
    try { recent.push({ id: directory.name, mtime: (await fs.lstat(path.join(root, directory.name, 'report.json'))).mtimeMs }) } catch {}
  }
  for (const item of recent.sort((a, b) => b.mtime - a.mtime).slice(0, 100)) {
    try { items.push(await getAudit(item.id)) } catch { /* An incomplete/corrupt audit must not hide valid reports. */ }
  }
  return items.sort((a, b) => b.createdAt.localeCompare(a.createdAt))
}
export async function getAudit(id) { return loadReport(await auditDirectory(id), id) }
export async function readAuditSession(id, sessionId) {
  if (typeof sessionId !== 'string' || !SESSION_ID.test(sessionId)) fail('Invalid session ID.')
  const directory = await auditDirectory(id)
  const report = await loadReport(directory, id)
  if (!report.sessions.some(session => session.id === sessionId)) fail('This session does not belong to this audit.')
  const history = JSON.parse((await readBounded(path.join(directory, `${sessionId}.json`), MAX_HISTORY_BYTES)).text)
  if (history.session?.id !== sessionId || !Array.isArray(history.messages)) fail('Invalid session snapshot.')
  return history
}

/** Validate proposed claims against the stored snapshot, including exact quotes
 * and message ordering. The semantic analysis is supplied by the user's agent. */
export async function submitAudit(id, submission) {
  return withAuditLock(id, async (directory, report) => {
    if (report.status === 'applied') fail('An applied audit cannot be edited. Start a new audit.')
    if (!submission || typeof submission !== 'object') fail('An audit submission is required.')
    const findings = array(submission.findings, 'Findings', 100)
    const observations = array(submission.observations, 'Observations', 1_000)
    const limitations = array(submission.limitations, 'Limitations', 50).map(value => string(value, 'Limitation', 2_000))
    const histories = new Map()
    const getHistory = async sessionId => {
      if (!histories.has(sessionId)) histories.set(sessionId, await readAuditSession(id, sessionId))
      return histories.get(sessionId)
    }
    const ids = new Set()
    const cleanFindings = []
    for (const finding of findings) {
      if (!finding || typeof finding !== 'object') fail('Invalid finding.')
      const findingId = string(finding.id, 'Finding ID', 80)
      if (!/^[a-zA-Z0-9_-]+$/.test(findingId) || ids.has(findingId)) fail('Finding IDs must be unique and contain only letters, numbers, underscores or hyphens.')
      ids.add(findingId)
      const clean = { id: findingId, title: string(finding.title, 'Finding title', 200), category: enumeration(finding.category, ['preference', 'workflow', 'context', 'tooling'], 'finding category'), summary: string(finding.summary, 'Finding summary', 5_000), confidence: enumeration(finding.confidence, ['low', 'medium', 'high'], 'confidence'), evidence: [] }
      if (!array(finding.evidence, 'Evidence', 20).length) fail('Every finding requires evidence from an included conversation.')
      for (const evidence of finding.evidence) {
        if (!evidence || typeof evidence !== 'object') fail('Invalid evidence.')
        const excerpt = string(evidence.excerpt, 'Evidence excerpt', 4_000)
        const history = await getHistory(evidence.sessionId)
        const message = history.messages.find(item => item.id === evidence.messageId)
        if (!message || !message.text.includes(excerpt)) fail(`Evidence for ${findingId} must exactly quote the specified recorded message.`)
        clean.evidence.push({ sessionId: evidence.sessionId, messageId: evidence.messageId, excerpt })
      }
      if (finding.proposal !== undefined) {
        clean.proposal = { before: string(finding.proposal?.before, 'Original proposal text', MAX_TARGET_BYTES, true), after: string(finding.proposal?.after, 'Proposed text', 100_000, true), rationale: string(finding.proposal?.rationale, 'Proposal rationale', 5_000) }
        const preview = previewAudit(report.original, [clean], [{ findingId, after: clean.proposal.after }])
        if (preview.conflicts.length) fail(`Invalid proposal for ${findingId}: ${preview.conflicts[0].message}`)
      }
      cleanFindings.push(clean)
    }
    const cleanObservations = []
    const requests = new Set()
    for (const observation of observations) {
      if (!observation || typeof observation !== 'object') fail('Invalid observation.')
      const history = await getHistory(observation.sessionId)
      const messages = history.messages
      const requestIndex = messages.findIndex(message => message.id === observation.requestMessageId)
      if (requestIndex < 0 || messages[requestIndex].role !== 'user') fail('An observed request must reference a recorded user message.')
      const key = `${observation.sessionId}:${observation.requestMessageId}`
      if (requests.has(key)) fail('A request may only have one observation.')
      requests.add(key)
      const completionIndex = observation.completionMessageId === undefined ? -1 : messages.findIndex(message => message.id === observation.completionMessageId)
      if (observation.completionMessageId !== undefined && (completionIndex <= requestIndex || messages[completionIndex]?.role !== 'assistant')) fail('Completion must reference an assistant message after the request.')
      const validationIndex = observation.validationMessageId === undefined ? -1 : messages.findIndex(message => message.id === observation.validationMessageId)
      if (observation.validationMessageId !== undefined && (completionIndex < 0 || validationIndex <= completionIndex || messages[validationIndex]?.role !== 'user')) fail('Validation must reference a user message after the assistant completion.')
      const outcome = enumeration(observation.outcome, ['validated', 'declared', 'unknown'], 'observation outcome')
      if (outcome === 'validated' && validationIndex < 0) fail('Validated outcomes require explicit user validation.')
      if (outcome === 'declared' && completionIndex < 0) fail('Declared outcomes require an assistant completion.')
      if (outcome !== 'validated' && validationIndex >= 0) fail('User validation requires a validated outcome.')
      const correctionIds = array(observation.correctionMessageIds, 'Correction IDs', 100)
      if (new Set(correctionIds).size !== correctionIds.length) fail('Correction message IDs must be unique.')
      for (const correction of correctionIds) {
        const index = messages.findIndex(message => message.id === correction)
        if (index <= requestIndex || messages[index]?.role !== 'user' || (validationIndex >= 0 && index >= validationIndex)) fail('Corrections must be user messages after the request and before any validation.')
      }
      const clean = { sessionId: observation.sessionId, requestMessageId: observation.requestMessageId,
        ...(completionIndex >= 0 ? { completionMessageId: observation.completionMessageId } : {}), ...(validationIndex >= 0 ? { validationMessageId: observation.validationMessageId } : {}), correctionMessageIds: [...correctionIds], outcome }
      const elapsed = index => {
        if (index < 0 || !messages[requestIndex].timestamp || !messages[index].timestamp) return undefined
        const value = Date.parse(messages[index].timestamp) - Date.parse(messages[requestIndex].timestamp)
        return Number.isFinite(value) && value >= 0 ? value : undefined
      }
      if (completionIndex >= 0) clean.responseTurns = messages.slice(requestIndex + 1, completionIndex + 1).filter(message => message.role === 'assistant').length
      if (elapsed(completionIndex) !== undefined) clean.elapsedMs = elapsed(completionIndex)
      if (elapsed(validationIndex) !== undefined) clean.validatedElapsedMs = elapsed(validationIndex)
      cleanObservations.push(clean)
    }
    report.findings = cleanFindings
    report.observations = cleanObservations
    report.limitations = [...new Set([...report.limitations, ...limitations])]
    report.status = 'ready'
    report.updatedAt = nextTimestamp(report.updatedAt)
    await atomicJSON(path.join(directory, 'report.json'), report)
    return report
  })
}

/** Apply only selected, possibly edited proposals. Recheck the exact snapshot,
 * preserve an exclusive backup, and replace atomically in the same directory. */
export async function applyAudit(id, decisions, expectedUpdatedAt) {
  return withAuditLock(id, async (directory, report) => {
    if (expectedUpdatedAt !== undefined && expectedUpdatedAt !== report.updatedAt) fail('The audit proposals changed since you reviewed them. Review the latest proposals before applying.')
    if (report.status !== 'ready') fail(report.status === 'applied' ? 'This audit has already been applied.' : 'Finish the audit analysis before applying proposals.')
    if (!array(decisions, 'Decisions', 100).length) fail('Select at least one proposal to apply.')
    const preview = previewAudit(report.original, report.findings, decisions)
    if (preview.conflicts.length) fail(preview.conflicts.map(conflict => conflict.message).join(' '))
    if (Buffer.byteLength(preview.content) > MAX_TARGET_BYTES) fail('The proposed instruction file exceeds 1 MiB.')
    if (preview.content === report.original) fail('The selected proposals do not change the instruction file.')
    if (generated(preview.content)) fail('A proposal cannot turn an instruction file into a generated SpecDrive export.')
    const root = await storeRoot()
    const targetLock = path.join(root, `.target-${hash(report.targetPath)}.lock`)
    let lockHandle
    let temporary
    let temporaryHandle
    try {
      try { lockHandle = await fs.open(targetLock, constants.O_WRONLY | constants.O_CREAT | constants.O_EXCL | constants.O_NOFOLLOW, 0o600) }
      catch (error) { if (error.code === 'EEXIST') fail('This instruction file is already being updated. Retry after the current operation completes.'); throw error }
      const current = await verifySnapshot(report)
      let backupPath
      if (current.originalExists) {
        backupPath = `${report.targetPath}.specdrive-${id}.bak`
        let backup
        try { backup = await fs.open(backupPath, constants.O_WRONLY | constants.O_CREAT | constants.O_EXCL | constants.O_NOFOLLOW, current.mode) }
        catch (error) { if (error.code === 'EEXIST') fail('A backup already exists for this audit, possibly from an earlier attempt. Keep it and start a new audit; this attempt has not changed the instruction file.'); throw error }
        try { await backup.writeFile(current.original, 'utf8'); await backup.sync() } finally { await backup.close() }
      }
      temporary = path.join(path.dirname(report.targetPath), `.specdrive-${randomUUID()}.tmp`)
      temporaryHandle = await fs.open(temporary, constants.O_WRONLY | constants.O_CREAT | constants.O_EXCL | constants.O_NOFOLLOW, current.mode)
      await temporaryHandle.writeFile(preview.content, 'utf8')
      await temporaryHandle.sync()
      await temporaryHandle.close(); temporaryHandle = undefined
      await verifySnapshot(report)
      await fs.rename(temporary, report.targetPath)
      temporary = undefined
      report.status = 'applied'
      report.appliedAt = nextTimestamp(report.updatedAt)
      report.updatedAt = report.appliedAt
      if (backupPath) report.backupPath = backupPath
      report.appliedFindingIds = decisions.map(decision => decision.findingId)
      report.appliedDecisions = decisions.map(decision => ({ findingId: decision.findingId, after: decision.after }))
      await atomicJSON(path.join(directory, 'report.json'), report)
      return report
    } finally {
      await temporaryHandle?.close()
      if (temporary) await fs.unlink(temporary).catch(error => { if (error.code !== 'ENOENT') throw error })
      if (lockHandle) { await lockHandle.close(); await fs.unlink(targetLock) }
    }
  })
}
